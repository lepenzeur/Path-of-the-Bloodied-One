def _stage_map(path: Path):
    text = path.read_text(encoding="utf-8")
    return {m.group(1): m.group(2) for m in _STAGE_RE.finditer(text)}

def run(project_file: str) -> None:
    root = Path(project_file).resolve().parent
    cache = {}
    ordered_source = []

    # Reassemble the categorized source in its original top-level order, then
    # compile once. Thousands of tiny exec/compile calls would make startup worse;
    # this keeps the refactor physically modular without adding runtime overhead.
    for relative, stage_id in MANIFEST:
        path = root / relative
        stages = cache.get(relative)
        if stages is None:
            stages = _stage_map(path)
            cache[relative] = stages
        code = stages.get(stage_id)
        if code is None:
            raise RuntimeError(f"Missing source stage {stage_id} in {relative}")
        ordered_source.append(code)

    namespace = {
        "__name__": "__main__",
        "__file__": str(root / "main.py"),
        "__package__": None,
    }
    compiled = compile("".join(ordered_source), str(root / "main.py"), "exec")
    exec(compiled, namespace, namespace)
