def _stage_map(path: Path):
    text = path.read_text(encoding="utf-8")
    return {m.group(1): m.group(2) for m in _STAGE_RE.finditer(text)}

def run(project_file: str) -> None:
    root = Path(project_file).resolve().parent
    cache = {}
    ordered_source = []




    for relative, stage_id in MANIFEST:
        path = root / relative
        stages = cache.get(relative)
        if stages is None:
            stages = _stage_map(path)
            cache[relative] = stages
        code = stages.get(stage_id)
        if code is None:
            raise RuntimeError(f"Missing source stage {stage_id} in {relative}")
        ordered_source.append(code)
        if stage_id != "S2676":
            ordered_source.append("\n_agraphon_boot_pump()\n")

    namespace = {
        "__name__": "__main__",
        "__file__": str(root / "main.py"),
        "__package__": None,
    }
    last_pump = [0.0]

    def _agraphon_boot_pump():
        now = time.monotonic()
        if now - last_pump[0] < 0.025:
            return
        last_pump[0] = now
        pygame_mod = namespace.get("pygame")
        if pygame_mod is None:
            return
        try:
            if pygame_mod.get_init() and pygame_mod.display.get_init() and pygame_mod.display.get_surface() is not None:
                pygame_mod.event.pump()
        except Exception as exc:
            BOOT_DIAGNOSTICS.append((type(exc).__name__, str(exc)))
            del BOOT_DIAGNOSTICS[:-32]

    namespace["_agraphon_boot_pump"] = _agraphon_boot_pump
    compiled = compile("".join(ordered_source), str(root / "main.py"), "exec")
    exec(compiled, namespace, namespace)
